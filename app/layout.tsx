import type { Metadata } from "next"
import localFont from "next/font/local"
import { ReactLenis } from "lenis/react"
import "lenis/dist/lenis.css"
import "./globals.css"
import Navbar from "@/components/navigation/Navbar"
import TransitionControl from "@/components/transition/TransitionControl"
import Sidebar from "@/components/sidebar/Sidebar"
import MobileSheet from "@/components/mobile-sheet/MobileSheet"
import Footer from "@/components/sections/Footer"
import PointerOverlay from "@/components/pointer/PointerOverlay"
import { GeneralInformationProvider } from "@/store/GeneralInformationStore"
import { getGeneralInformation } from "@/utils/sanityGetters"

const sans = localFont({
	src: "../fonts/font-sans.woff2",
	variable: "--font-sans-local",
	weight: "300 900",
	style: "normal",
	display: "swap",
})

const serif = localFont({
	src: "../fonts/font-serif.woff2",
	variable: "--font-serif-local",
	weight: "200 700",
	style: "normal",
	display: "swap",
})

export const metadata: Metadata = {
	title: "Create Next App",
	description: "Generated by create next app",
}

// Fetched here rather than in the two components that print it. The footer and the sidebar menu both
// show the studio's contact details, and both are client components that cannot await anything — so
// the one place with a server render and a view of both of them is this layout. Cached for an hour
// (see getGeneralInformation), which is what keeps every route in the site from blocking on Sanity
// to render its footer.
export default async function RootLayout({ children }: LayoutProps<"/">) {
	const general = await getGeneralInformation()

	return (
		<html
			lang="en"
			className={`${sans.variable} ${serif.variable} h-full antialiased`}
		>
			<body className="min-h-screen">
				{/* Wraps the whole body because the two readers are at opposite ends of it: Footer
				    below, and the sidebar menu, which Sidebar renders here even though the element
				    itself is built inside SidebarContentStore. Context resolves where a node is
				    RENDERED, not where it was created, so the menu finds this the same as the footer
				    does. */}
				<GeneralInformationProvider information={general}>
					{/* Above TransitionControl, which calls useLenis to jump each incoming page to the
					    top. */}
					<ReactLenis root/>
					{/* Holds the page being left on screen until the one arriving has signalled ready,
					    and covers the swap with the curtain. Navbar stays outside it so it survives the
					    swap rather than being torn down and rebuilt on every navigation. */}
					<TransitionControl>{children}</TransitionControl>
					<Navbar />
					<Sidebar />
					<MobileSheet />
					{/* One for the document, drawn here and told what to say by whatever the pointer is
					    over. In the layout rather than in any page, so it survives a navigation the same
					    way the navbar does. */}
					<PointerOverlay />
					<Footer />
				</GeneralInformationProvider>
			</body>
		</html>
	)
}
