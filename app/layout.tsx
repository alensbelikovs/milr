import type { Metadata } from "next"
import localFont from "next/font/local"
import { ReactLenis } from "lenis/react"
import "lenis/dist/lenis.css"
import "./globals.css"
import Navbar from "@/components/navigation/Navbar"
import PointerOverlay from "@/components/pointer/PointerOverlay"
import Footer from "@/components/sections/Footer"
import Sidebar from "@/components/sidebar/Sidebar"
import TransitionControl from "@/components/transition/TransitionControl"
import { GeneralInformationProvider } from "@/store/GeneralInformationStore"
import { getGeneralInformation } from "@/utils/sanityGetters"

const sans = localFont({
	src: "../fonts/font-sans.woff2",
	variable: "--font-sans-local",
	weight: "300 900",
	style: "normal",
	display: "swap",
})

const serif = localFont({
	src: "../fonts/font-serif.woff2",
	variable: "--font-serif-local",
	weight: "200 700",
	style: "normal",
	display: "swap",
})

export const metadata: Metadata = {
	title: "Create Next App",
	description: "Generated by create next app",
}

// General information is fetched here once, for the client components that show it (footer, menu, contact)
export default async function RootLayout({ children }: LayoutProps<"/">) {
	const general = await getGeneralInformation()

	return (
		<html lang="en" className={`${sans.variable} ${serif.variable} h-full antialiased`}>
			<body className="min-h-screen">
				<GeneralInformationProvider information={general}>
					{/* Before TransitionControl, which uses Lenis to scroll each new page to the top */}
					<ReactLenis root />
					<TransitionControl>{children}</TransitionControl>
					<Navbar />
					<Sidebar />
					<PointerOverlay />
					<Footer />
				</GeneralInformationProvider>
			</body>
		</html>
	)
}
